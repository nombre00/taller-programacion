CREATE TABLE MensajeContacto (
    id_mensaje      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre_remitente VARCHAR2(255) NOT NULL,
    email_remitente VARCHAR2(255) NOT NULL,
    asunto          VARCHAR2(255),
    mensaje         VARCHAR2(4000) NOT NULL,
    fecha_recibido  DATE DEFAULT SYSDATE NOT NULL,
    leido           NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_mensaje_contacto PRIMARY KEY (id_mensaje),
    CONSTRAINT chk_mensaje_leido CHECK (leido IN (0, 1))
);



CREATE TABLE PAGO (
    id_pago NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_pago VARCHAR2(50),
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    id_pago_mpos VARCHAR2(100),
    id_pedido NUMBER NOT NULL,
    id_preferencia_mpos VARCHAR2(200),
    metodo_pago VARCHAR2(50),
    monto_pago NUMBER(10,2),
    respuesta_mercado_pago CLOB,
    CONSTRAINT fk_pago_pedido FOREIGN KEY (id_pedido) REFERENCES PEDIDO(id_pedido)
